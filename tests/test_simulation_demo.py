def run_test():
    builder = e.DirectorPromptBuilder(
        MODE, STYLE, COLOR, TOPIC, CHARACTER, ENV, SHOTS,
        camera_style="炫酷动感", is_vertical=False,
        director_keys=DIRECTORS, narrative_structure=NARRATIVE,
    )
    header = builder.build_header()
    segments = []
    constraints = ShotConstraints()

    print("=" * 70)
    print("【测试启动】知识库驱动的世界级导演引擎 V4.0")
    print(f"导演组合: 徐克(飘逸奇幻) + 塔伦蒂诺(章节/黑幽默)")
    print(f"类型: 神话史诗风 | 叙事结构: 自动适配 → {builder.narrative_structure}")
    print(f"新增: ①张弛节奏指导 ②按叙事功能推断表演情绪 ③叙事契合原因")
    print("=" * 70)

    for i in range(SHOTS):
        beat = {
            "beat_name": ["冷开场","暗线铺设","一打识破","中点暴露","三打决战","余韵收束"][i],
            "emotion_value": [0.6, 0.5, 0.7, 0.65, 0.9, 0.3][i],
            "intensity":    [0.5, 0.4, 0.75, 0.7, 0.95, 0.4][i],
            "narrative_func": ["章节冷开场","无间道暗线铺设","一打识破","中点背叛暴露","三打终极对决","代价余韵收束"][i],
            "story_progress": (i+1)/SHOTS,
            "recommended_shot_types": ["极远景","双人景","全身","过肩","全景","中远景"][i].split("/"),
        }
        # 真实构建系统提示词(展示知识库注入)
        sys_p = builder.build_system_prompt(i, beat, constraints.get_constraints_text())
        # 模拟AI返回
        ai_result = SIM_OUTPUTS[i]
        # 真实记录,累积故事前文
        builder.record_shot_result(i, ai_result, beat)

        seg = f"{header}\n【镜头{i+1}/{SHOTS}】\n{ai_result}\n"
        segments.append(seg)

        # 打印第1镜(开场)和第5镜(爆发)和第6镜(余韵)的系统提示词,展示节奏差异
        if i in (0, 4, 5):
            print(f"\n{'─'*70}\n【第{i+1}镜 系统提示词】长度{len(sys_p)}字符:\n{'─'*70}")
            print(sys_p)

    # 汇总: 整条故事线的节奏与情绪推进(张弛有度验证)
    print("\n" + "=" * 70)
    print("【故事线节奏与情绪推进汇总 — 张弛有度验证】")
    print("=" * 70)
    funcs = ["章节冷开场","无间道暗线铺设","一打识破","中点背叛暴露","三打终极对决","代价余韵收束"]
    intensities = [0.5, 0.4, 0.75, 0.7, 0.95, 0.4]
    for i, (f, inten) in enumerate(zip(funcs, intensities)):
        beat = {"narrative_func": f, "emotion_value": 0.6, "intensity": inten,
                "story_progress": (i+1)/6}
        phase = builder._identify_pace_phase((i+1)/6, inten, f, i, 6)
        emo = builder._infer_emotion(beat, i)
        bar = "▁▂▃▄▅▆▇█"[min(7, int(inten*8))]
        print(f"  镜{i+1} {f:12s} | {bar} 强度{inten:.2f} | 节奏:{phase[:6]:6s} | 表演情绪:{emo}")

    output = PromptSegmenter.join_outputs(segments)
    print("\n" + "=" * 70)
    print("【最终批次分镜输出】")
    print("=" * 70)
    print(output)
    return output


if __name__ == "__main__":
    run_test()
